function runCurrentTool() {
  const spec = currentToolSpec();
  const board = currentBoard();
  const out = document.getElementById("toolOut")!;
  if (!spec) return;
  if (!board) { out.textContent = "Load a board first."; out.classList.add("err"); return; }
  if (!wasm) { out.textContent = wasmStatus || "wasm not ready"; out.classList.add("err"); return; }
  const args = buildArgsJson(spec);
  let result: string;
  try { result = wasmRunTool(serializeViewBoard(board), spec.name, args); }
  catch (e) { result = "error: " + e; }
  const isErr = result.startsWith("error:");
  out.textContent = result;
  out.classList.toggle("err", isErr);
  // Scrollback (most-recent first, capped).
  toolLog.unshift({ call: `${spec.name}(${args})`, out: result, err: isErr });
  if (toolLog.length > 20) toolLog.pop();
  renderToolLog();
}

