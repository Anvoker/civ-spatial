// Fill the focused tool field from a clicked tile: coord pairs set both x/y; unit fields take a unit
// id on the tile (with a chooser when several are stacked); terrain/resource/player fields read the
// tile's own facts. No-op when no field is focused.
function toolsPickTile(x: number, y: number, board: BoardD) {
  const units = document.getElementById("toolUnits");
  if (units) units.innerHTML = "";
  if (!activeArgKey) return;
  const key = activeArgKey;
  const pair = coordPair(key);
  if (pair) {
    const [kx, ky] = pairKeys(pair);
    const ix = toolInput(kx), iy = toolInput(ky);
    if (ix) ix.value = String(x);
    if (iy) iy.value = String(y);
    return;
  }
  const vw = currentView(board);
  if (UNIT_FIELDS.has(key)) {
    const here = vw.units.filter(u => u.x === x && u.y === y);
    const inp = toolInput(key);
    if (!here.length) { const h = document.getElementById("toolPickHint")!; h.textContent = `no units on (${x}, ${y})`; return; }
    if (inp) inp.value = String(here[0].id);
    if (here.length > 1 && units) { // stacked: offer a chooser
      for (const u of here) {
        const b = document.createElement("button"); b.className = "btn";
        b.textContent = `#${u.id} ${u.kind}`;
        b.onclick = () => { const i = toolInput(key); if (i) i.value = String(u.id); };
        units.appendChild(b);
      }
    }
    return;
  }
  // string facts
  const t = vw.tiles[y * board.width + x];
  if (key === "terrain" && t) { const i = toolInput(key); if (i) i.value = t.terrain; return; }
  if (key === "resource" && t) {
    const infra = new Set(["River", "Road", "Railroad", "Irrigation", "Mine", "Farmland", "Fortress", "Airbase", "Pollution", "Fallout", "Hut"]);
    const res = t.extras.find(e => !infra.has(e));
    const i = toolInput(key); if (i && res) i.value = res; return;
  }
  if ((key === "player" || key === "exclude_owner") && t && t.owner) { const i = toolInput(key); if (i) i.value = t.owner; return; }
}

