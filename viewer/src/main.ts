// Owner colors are assigned by a STABLE INDEX over the set of owners actually present on the board
// (sorted for determinism), NOT by hash(name) mod N — the old hash scheme collided (e.g. "Unassigned5"
// and "Testcontroller" both landed on the same yellow). Distinct up to the palette size; only when a
// board has more owners than colors do we wrap (and the legend then shows the shared swatch honestly).
const OWNER_COLORS = ["#e15554", "#4d9de0", "#e1bc29", "#7768ae", "#3bb273",
  "#e07b39", "#d16ba5", "#5c9ead", "#b5651d", "#8a89a6"];
const OWNER_FALLBACK = "#9aa0a6"; // for an owner not in the current board's index (shouldn't happen)
let ownerColorMap: Record<string, string> = {};
let ownerOrder: string[] = []; // owners in the order they were assigned colors (for the legend)
let nationMap: Record<string, string> = {}; // owner-identity (leader name) -> real nation

// Collect every owner that appears anywhere in a board view (territory, cities, units) plus the
// perspective player, then assign palette colors by sorted index. Colors key on the stable owner
// IDENTITY (leader name); the DISPLAY label (see ownerLabel) is the nation.
function buildOwnerColors(board: BoardD) {
  nationMap = {};
  for (const p of board.players ?? []) if (p.nation) nationMap[p.name] = p.nation;
  const owners = new Set<string>();
  const addContents = (c: BoardContentsD) => {
    for (const t of c.tiles) if (t.owner) owners.add(t.owner);
    for (const ct of c.cities) owners.add(ct.owner);
    for (const u of c.units) owners.add(u.owner);
  };
  addContents(board);
  if (board.unfogged) addContents(board.unfogged);
  if (board.perspective) owners.add(board.perspective);
  ownerOrder = [...owners].sort();
  ownerColorMap = {};
  ownerOrder.forEach((name, i) => { ownerColorMap[name] = OWNER_COLORS[i % OWNER_COLORS.length]; });
}
function ownerColor(name: string): string { return ownerColorMap[name] ?? OWNER_FALLBACK; }
// The user-facing label for an owner: its nation, falling back to the leader name when the nation is
// missing/empty. This is what keeps placeholder "UnassignedN" leader names off the display.
function ownerLabel(name: string): string { return nationMap[name] || name; }

function cssVar(name: string): string {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim() || "#888";
}

