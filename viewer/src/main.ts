// View transform helpers (Priority 2: zoom + pan)
// ---------------------------------------------------------------------------
function sizeCanvas() {
  const wrap = canvas.parentElement as HTMLElement | null;
  const cw = wrap && wrap.clientWidth ? wrap.clientWidth - 24 : 900;
  canvas.width = Math.max(320, Math.floor(cw));
  canvas.height = 520; // trimmed a little (was 600) to reclaim vertical space (item 2)
}
// Fit the whole board into the canvas with a small margin (the default, screenshot-friendly zoom).
function fitView(board: BoardD) {
  sizeCanvas();
  const pad = 14;
  const s = Math.min(
    (canvas.width - pad * 2) / (board.width * TILE),
    (canvas.height - pad * 2) / (board.height * TILE),
  );
  view.scale = s > 0 ? s : 1;
  view.tx = (canvas.width - board.width * TILE * view.scale) / 2;
  view.ty = (canvas.height - board.height * TILE * view.scale) / 2;
}
function clampScale(s: number): number { return Math.max(0.05, Math.min(24, s)); }
// Screen (backing-store) pixel -> world coordinate.
function screenToWorld(sx: number, sy: number): { x: number; y: number } {
  return { x: (sx - view.tx) / view.scale, y: (sy - view.ty) / view.scale };
}
// Mouse event -> backing-store pixel (accounts for CSS scaling of the canvas).
function eventToScreen(e: MouseEvent): { x: number; y: number } {
  const rect = canvas.getBoundingClientRect();
  const kx = canvas.width / (rect.width || canvas.width);
  const ky = canvas.height / (rect.height || canvas.height);
  return { x: (e.clientX - rect.left) * kx, y: (e.clientY - rect.top) * ky };
}

