// ---------------------------------------------------------------------------
// Tool playground — run ANY of the eval's model-facing tools against the CURRENT view board, through
// the REAL Rust dispatch compiled to wasm (civ_eval::run_tool). Nothing here re-implements a tool;
// parity with the eval is the whole point. The board is serialized to the export shape and handed to
// the wasm on each Run, so the Fog toggle (currentView) automatically re-targets the tools.
// ---------------------------------------------------------------------------
interface WasmExports {
  memory: WebAssembly.Memory;
  alloc(len: number): number;
  dealloc(ptr: number, len: number): void;
  run_tool(bp: number, bl: number, np: number, nl: number, ap: number, al: number): number;
}
let wasm: WasmExports | null = null;
let wasmStatus = "loading wasm…";

function initWasm() {
  const b64 = (window as unknown as { __CIVSPATIAL_WASM__?: string }).__CIVSPATIAL_WASM__;
  if (!b64) { wasmStatus = "tool wasm not bundled — run `npm run build:wasm`"; updateToolRunEnabled(); return; }
  try {
    const bin = atob(b64);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    WebAssembly.instantiate(bytes, {}).then(res => {
      wasm = res.instance.exports as unknown as WasmExports;
      wasmStatus = "";
      updateToolRunEnabled();
    }).catch(err => { wasmStatus = "wasm failed to load: " + err; updateToolRunEnabled(); });
  } catch (err) { wasmStatus = "wasm decode failed: " + err; updateToolRunEnabled(); }
}

// Marshal three strings across the raw C ABI and read back the length-prefixed result. Memory can
// grow during the call, so the result view is taken AFTER run_tool returns.
function wasmRunTool(boardJson: string, name: string, argsJson: string): string {
  if (!wasm) return wasmStatus || "wasm not ready";
  const w = wasm;
  const enc = new TextEncoder(), dec = new TextDecoder();
  const write = (s: string) => {
    const b = enc.encode(s);
    const ptr = w.alloc(b.length);
    new Uint8Array(w.memory.buffer).set(b, ptr);
    return { ptr, len: b.length };
  };
  const bj = write(boardJson), nm = write(name), ar = write(argsJson);
  const rptr = w.run_tool(bj.ptr, bj.len, nm.ptr, nm.len, ar.ptr, ar.len);
  const view = new DataView(w.memory.buffer);
  const len = view.getUint32(rptr, true);
  const out = dec.decode(new Uint8Array(w.memory.buffer).slice(rptr + 4, rptr + 4 + len));
  w.dealloc(rptr, 4 + len);
  w.dealloc(bj.ptr, bj.len); w.dealloc(nm.ptr, nm.len); w.dealloc(ar.ptr, ar.len);
  return out;
}

