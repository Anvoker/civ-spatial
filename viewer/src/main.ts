// Trident tileset (optional): window.__CIVSPATIAL_TILESET__ from src/tileset-data.js.
// ---------------------------------------------------------------------------
interface SpriteRect { sheet: string; x: number; y: number; w: number; h: number; }
interface TilesetD { sheets: Record<string, string>; sprites: Record<string, SpriteRect>; }

const TILESET: TilesetD | null =
  (window as unknown as { __CIVSPATIAL_TILESET__?: TilesetD }).__CIVSPATIAL_TILESET__ ?? null;
const sheetImages: Record<string, HTMLImageElement> = {};
let spritesReady = false;
let useSprites = true; // user toggle; only has effect when a tileset is loaded

// Map OUR terrain names -> trident `graphic_str` tags (isolated, non-blended representative sprite).
// Water (Ocean/Lake/Deep Ocean) and Unknown intentionally have no sprite -> flat color fallback.
const TERRAIN_SPRITE: Record<string, string> = {
  "Grassland": "t.l0.grassland1",
  "Plains": "t.l0.plains_n0e0s0w0",
  "Forest": "t.l0.forest_n0e0s0w0",
  "Hills": "t.l0.hills_n0e0s0w0",
  "Mountains": "t.l0.mountains_n0e0s0w0",
  "Desert": "t.l0.desert_n0e0s0w0",
  "Jungle": "t.l0.jungle_n0e0s0w0",
  "Swamp": "t.l0.swamp_n0e0s0w0",
  "Tundra": "t.l0.tundra_n0e0s0w0",
  "Glacier": "t.l0.arctic_n0e0s0w0", // freeciv calls glacier "arctic"
  "Inaccessible": "t.l0.inaccessible1",
};
// Unit-kind aliases where our name differs from the freeciv tag root.
const UNIT_ALIAS: Record<string, string> = { "workers": "worker" };

function spriteRect(tag: string): SpriteRect | null {
  if (!TILESET || !spritesReady || !useSprites) return null;
  return TILESET.sprites[tag] ?? null;
}
function unitTag(kind: string): string {
  const n = kind.toLowerCase().replace(/\./g, "").replace(/\s+/g, "_");
  return `u.${UNIT_ALIAS[n] ?? n}_Idle`;
}
function cityTag(size: number): string {
  const idx = size <= 4 ? 0 : size <= 8 ? 1 : 2;
  return `city.european_city_${idx}`;
}
// Blit a sprite centered in the given world rect. Returns false if the sprite/sheet is unavailable.
function blitSprite(tag: string, x: number, y: number, w: number, h: number): boolean {
  const r = spriteRect(tag);
  if (!r) return false;
  const img = sheetImages[r.sheet];
  if (!img || !img.complete || !img.naturalWidth) return false;
  ctx.drawImage(img, r.x, r.y, r.w, r.h, x, y, w, h);
  return true;
}

