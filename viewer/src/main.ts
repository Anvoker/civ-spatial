// CivSpatial Replay Viewer — vanilla TS + HTML5 canvas, no framework, no runtime deps.
// Loads the JSON emitted by `civ viewer-export` and lets you step through the questions a model
// went through: the board, the question's referents/candidates, model-vs-correct answer, and (for
// interactive encodings) the exploration trajectory. Fully offline; no LLM calls.
//
// Compiled to a single dist/viewer.js (tsconfig module:"none", outFile). No import/export here.
//
// Rendering: a pan/zoomable canvas over a "world" where each tile is TILE world-pixels. Terrain,
// cities and units are blitted from the GPL Freeciv `trident` OVERHEAD tileset when present
// (src/tileset-data.js, generated by scripts/build-tileset.mjs) and fall back to flat color when a
// sprite or the asset bundle is missing.

// ---------------------------------------------------------------------------
// JSON contract (mirrors civ-cli/src/viewer_export.rs)
// ---------------------------------------------------------------------------
interface TileD { x: number; y: number; terrain: string; extras: string[]; owner: string | null; }
// `improvements` (City Walls / Coastal Defense / Great Wall / Palace / …) is load-bearing for the
// tool playground's wall/coastal/Great-Wall/Palace math; older exports omit it (treated as none).
interface CityD { x: number; y: number; id: number; name: string; owner: string; size: number; improvements?: string[]; }
interface UnitD { x: number; y: number; id: number; kind: string; owner: string; veteran: number; hp: number; }
interface BoardContentsD { tiles: TileD[]; cities: CityD[]; units: UnitD[]; }
interface PlayerD { name: string; nation: string; }
interface BoardD extends BoardContentsD {
  source: string; width: number; height: number;
  // Fog metadata (optional; older exports omit them). `perspective` is the fogging player ("you").
  // `unfogged` is the full ground-truth board present only when this board is a fogged view.
  perspective?: string;
  unfogged?: BoardContentsD;
  // Player roster: leader `name` (the owner-identity string) -> real `nation`. Owners are LABELED by
  // nation so placeholder leader names ("Unassigned5") don't surface. Optional/backward-compatible.
  players?: PlayerD[];
}
interface PointD { kind: "tile" | "city" | "unit"; x: number; y: number; id?: number; label?: string; }
interface BBox { x0: number; y0: number; x1: number; y1: number; }
interface ToolCallD { name: string; args: string; region: BBox | null; }
interface TurnD { tool_calls: ToolCallD[]; fetched_regions: BBox[]; text: string; reasoning?: string; }
interface QuestionD {
  item_id: string; category: string; tier: string; encoding: string; board_ref: string;
  model?: string;         // run/model label (e.g. "DeepSeek", "Haiku p1") for merged multi-run bundles
  question_text: string;
  full_prompt?: string;   // the FULL turn-0 prompt (instructions + board preamble + question)
  model_answer: string;   // the PARSED answer (`result.got`); empty when scoring couldn't parse it
  answer_text?: string;   // the model's RAW completion text (shown when model_answer is empty)
  correct_answer: string; status: string;
  referents: PointD[]; candidates: PointD[]; options: string[]; radius?: number;
  reasoning?: string;     // model reasoning, when the trace carried it (static or interactive)
  trajectory?: TurnD[];
  // Aggregate per-question metrics summed over the trace's turns (added by viewer_export.rs). Present
  // on newer exports; older ones omit them (guarded at read sites). `cached_tokens` is the cache-hit
  // SUBSET of `prompt_tokens` (not additive); there is no total_tokens (total = prompt + completion).
  latency_ms?: number;
  prompt_tokens?: number; completion_tokens?: number; cached_tokens?: number;
  n_turns?: number; n_tool_calls?: number;
  tool_call_counts?: Record<string, number>; // tool name -> call count over ALL turns (all tool-using encodings)
  trace_file?: string;    // source trace filename — the unique key for the copy-identifier
}
interface ExportD {
  boards: Record<string, BoardD>;
  questions: QuestionD[];
  meta?: { trace_dir?: string; model?: string; models?: string[]; n_questions?: number; n_boards?: number };
}

