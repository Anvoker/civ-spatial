function loadData(d: ExportD) {
  DATA = d;
  const meta = d.meta || {};
  const modelBits = (meta.models && meta.models.length)
    ? ` · runs: ${meta.models.join(", ")}`
    : (meta.model ? ` · model: ${meta.model}` : "");
  $("metaLine").textContent =
    `${d.questions.length} questions · ${Object.keys(d.boards).length} board(s)` + modelBits;
  viewInitForBoard = null;
  populateFilters();
  applyFilters();
  if (filtered.length) selectQuestion(0);
  // The Stats / Compare view renders permanently below the replay layout — rebuild it against new data.
  renderStats();
}

function populateFilters() {
  if (!DATA) return;
  const cats = new Set<string>(), encs = new Set<string>(), models = new Set<string>();
  for (const q of DATA.questions) {
    cats.add(q.category); encs.add(q.encoding);
    if (q.model) models.add(q.model);
  }
  // The run/model filter only makes sense (and only appears) when the bundle mixes runs.
  const modelSel = document.getElementById("fModel") as HTMLSelectElement | null;
  if (modelSel) {
    if (models.size > 1) { fillSelect(modelSel, models, "All runs"); modelSel.hidden = false; }
    else { modelSel.hidden = true; modelSel.value = ""; }
  }
  fillSelect($("fCategory") as HTMLSelectElement, cats, "All categories");
  fillSelect($("fEncoding") as HTMLSelectElement, encs, "All encodings");
}
function fillSelect(sel: HTMLSelectElement, values: Set<string>, allLabel: string) {
  const cur = sel.value;
  sel.innerHTML = "";
  const all = document.createElement("option"); all.value = ""; all.textContent = allLabel;
  sel.appendChild(all);
  for (const v of [...values].sort()) {
    const o = document.createElement("option"); o.value = v; o.textContent = v; sel.appendChild(o);
  }
  sel.value = cur;
}

// Normalize scoring status into one of the three viewer buckets.
function statusBucket(status: string): "correct" | "wrong" | "invalid" {
  const s = status.toLowerCase();
  if (s === "correct") return "correct";
  if (s === "invalid" || s === "off-board" || s === "unparseable" || s === "refused") return "invalid";
  return "wrong";
}

// Filter the loaded question set by category / encoding / result. Shared by the replay list and the
// Stats / Compare view (item 7) so both honor exactly the same filter logic. Empty string = "all".
function filterQuestions(fc: string, fe: string, fs: string, fm = ""): QuestionD[] {
  if (!DATA) return [];
  return DATA.questions.filter(q =>
    (!fc || q.category === fc) && (!fe || q.encoding === fe) &&
    (!fs || statusBucket(q.status) === fs) && (!fm || q.model === fm));
}

function applyFilters() {
  if (!DATA) return;
  const modelSel = document.getElementById("fModel") as HTMLSelectElement | null;
  filtered = filterQuestions(
    ($("fCategory") as HTMLSelectElement).value,
    ($("fEncoding") as HTMLSelectElement).value,
    ($("fStatus") as HTMLSelectElement).value,
    modelSel && !modelSel.hidden ? modelSel.value : "");
  renderList();
  if (selectedIndex >= filtered.length) selectedIndex = filtered.length - 1;
}

// ---------------------------------------------------------------------------
// Question list (grouped by category × encoding)
// ---------------------------------------------------------------------------
function renderList() {
  const host = $("qlist"); host.innerHTML = "";
  if (!filtered.length) { host.innerHTML = `<div class="empty">No questions match.</div>`; return; }
  const groups = new Map<string, QuestionD[]>();
  for (const q of filtered) {
    const key = (q.model ? `${q.model} · ` : "") + `${q.category} · ${q.encoding}`;
    (groups.get(key) ?? groups.set(key, []).get(key)!).push(q);
  }
  for (const [key, qs] of groups) {
    const h = document.createElement("div"); h.className = "qgroup-h";
    const nPass = qs.filter(q => statusBucket(q.status) === "correct").length;
    h.textContent = `${key}  (${nPass}/${qs.length} correct)`;
    host.appendChild(h);
    for (const q of qs) {
      const idx = filtered.indexOf(q);
      const row = document.createElement("div");
      row.className = "qitem" + (idx === selectedIndex ? " active" : "");
      const bucket = statusBucket(q.status);
      row.innerHTML =
        `<span class="qid">${escapeHtml(shortId(q.item_id))}</span>` +
        `<span class="badge ${bucket}">${bucket === "correct" ? "PASS" : bucket === "wrong" ? "FAIL" : "INV"}</span>`;
      row.title = q.item_id;
      row.onclick = () => selectQuestion(idx);
      host.appendChild(row);
    }
  }
}
function shortId(id: string): string {
  const c = id.indexOf(":");
  return c >= 0 ? id.slice(c + 1) : id;
}
function escapeHtml(s: string): string {
  return s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
}

// ---------------------------------------------------------------------------
// Selection
// ---------------------------------------------------------------------------
function selectQuestion(idx: number) {
  if (idx < 0 || idx >= filtered.length) return;
  selectedIndex = idx;
  const q = filtered[idx];
  stepTurn = q.trajectory && q.trajectory.length ? 0 : -1;
  renderList();
  renderAnswer(q);
  renderStepper(q);
  updateFogBtn();
  updateCenterTitle(q);
  refreshToolPlayerDefaults();
  updatePickHint();
  drawBoard();
  ($("prevBtn") as HTMLButtonElement).disabled = idx <= 0;
  ($("nextBtn") as HTMLButtonElement).disabled = idx >= filtered.length - 1;
}

function currentQuestion(): QuestionD | null {
  return selectedIndex >= 0 && selectedIndex < filtered.length ? filtered[selectedIndex] : null;
}
function currentBoard(): BoardD | null {
  const q = currentQuestion();
  if (!q || !DATA) return null;
  return DATA.boards[q.board_ref] ?? null;
}
// Whether the current board can toggle fog (i.e. carries a distinct ground-truth companion).
function boardHasFog(board: BoardD | null): boolean { return !!(board && board.unfogged); }
// The tiles/cities/units to actually render: the fogged (as-seen) view unless fog is toggled off and
// a ground-truth companion exists. Backward compatible: boards without `unfogged` always render as-is.
function currentView(board: BoardD): BoardContentsD {
  return (!showFog && board.unfogged) ? board.unfogged : board;
}

// ---------------------------------------------------------------------------
// Answer panel — Priority 1: show the MODEL'S answer prominently alongside the correct one.
// ---------------------------------------------------------------------------
function renderAnswer(q: QuestionD) {
  const bucket = statusBucket(q.status);
  const el = $("answer");
  el.innerHTML = "";

  // Pass/fail chip.
  const pill = document.createElement("div");
  pill.className = `pill ${bucket}`;
  pill.textContent = bucket === "correct" ? "CORRECT" : bucket === "wrong" ? "WRONG" : q.status.toUpperCase();
  el.appendChild(pill);

  // The headline: model answer vs correct answer, side by side.
  const modelParsed = q.model_answer && q.model_answer.trim();
  const cmp = document.createElement("div");
  cmp.className = "answercmp";
  cmp.appendChild(bigAnswer("Model answered", modelParsed ? q.model_answer : "(unparseable)", bucket, !modelParsed));
  cmp.appendChild(bigAnswer("Correct answer", q.correct_answer || "—", "correct", false));
  el.appendChild(cmp);

  // Metadata rows.
  const modelName = q.model || (DATA && DATA.meta && DATA.meta.model) || "";
  if (modelName) el.appendChild(kv(q.model ? "Run" : "Model", modelName));
  el.appendChild(kv("Category", `${q.category}  (${q.tier})`));
  el.appendChild(kv("Encoding", q.encoding));
  if (q.options && q.options.length) el.appendChild(kv("Options", q.options.join(" | ")));

  // Latency + token + turn/tool-call metrics (summed over the trace's turns), when the export carries
  // them. cached is the cache-hit SUBSET of prompt (shown as "X cached", never added into a total).
  const m = metricsBlock(q); if (m) el.appendChild(m);

  // Collapsible sections (item 2), same treatment as the full prompt. The question moved here from the
  // board window; it stays open by default (open once its board eats less vertical space). The model's
  // raw answer text and the reasoning are collapsed by default so they don't dominate.
  const qtext = (q.question_text || "").trim(); // some exports carry a leading "\n\nQUESTION:" gap
  if (qtext) el.appendChild(collapsible("Question", qtext, { open: true }));

  // The model's raw completion text — the ONLY place the answer survives when parsing failed
  // (status=invalid). This is the field the previous build dropped.
  if (q.answer_text && q.answer_text.trim())
    el.appendChild(collapsible("Model's answer text", q.answer_text, { mono: true }));

  // Reasoning: explicit trace reasoning, else the last trajectory turn's `.reasoning` (item 4 fix —
  // no longer the turn's answer text). Omitted entirely when the trace carried no reasoning.
  const reasoning = q.reasoning && q.reasoning.trim() ? q.reasoning : lastReasoning(q);
  if (reasoning) el.appendChild(collapsible("Reasoning", reasoning, { muted: true }));

  // Full prompt / system — the entire turn-0 prompt (instructions + board preamble + question),
  // collapsed by default so it doesn't dominate. (Intentionally left untrimmed.)
  if (q.full_prompt && q.full_prompt.trim())
    el.appendChild(collapsible(`Full prompt / system  (${q.full_prompt.length.toLocaleString()} chars)`, q.full_prompt, { mono: true }));
}
// A collapsible <details> section — the shared "same treatment the full prompt already has" (item 2).
function collapsible(label: string, text: string, opts: { open?: boolean; mono?: boolean; muted?: boolean } = {}): HTMLElement {
  const det = document.createElement("details"); det.className = "collapse";
  if (opts.open) det.open = true;
  const sum = document.createElement("summary"); sum.textContent = label;
  const body = document.createElement("div");
  body.className = "collapsebody" + (opts.mono ? " mono" : "") + (opts.muted ? " muted" : "");
  body.textContent = text;
  det.appendChild(sum); det.appendChild(body);
  return det;
}
// A large, prominent answer block (model vs correct).
function bigAnswer(label: string, value: string, tone: "correct" | "wrong" | "invalid", muted: boolean): HTMLElement {
  const box = document.createElement("div");
  box.className = `bigans ${tone}` + (muted ? " muted" : "");
  const l = document.createElement("div"); l.className = "l"; l.textContent = label;
  const v = document.createElement("div"); v.className = "v"; v.textContent = value;
  box.appendChild(l); box.appendChild(v);
  return box;
}
function kv(k: string, v: string): HTMLElement {
  const row = document.createElement("div"); row.className = "ansrow";
  row.innerHTML = `<span class="k">${escapeHtml(k)}</span><span class="v">${escapeHtml(v)}</span>`;
  return row;
}
// A small grid of stat tiles: latency, tokens, cached, turns/tool-calls. Returns null when the export
// carries none of the aggregate metrics (older exports).
function metricsBlock(q: QuestionD): HTMLElement | null {
  const has = q.latency_ms != null || q.prompt_tokens != null || q.completion_tokens != null ||
    q.n_turns != null || q.n_tool_calls != null;
  if (!has) return null;
  const wrap = document.createElement("div"); wrap.className = "metrics";
  const cell = (label: string, value: string, sub?: string) => {
    const c = document.createElement("div"); c.className = "metric";
    const l = document.createElement("div"); l.className = "ml"; l.textContent = label;
    const v = document.createElement("div"); v.className = "mv"; v.textContent = value;
    c.appendChild(l); c.appendChild(v);
    if (sub) { const s = document.createElement("div"); s.className = "ms"; s.textContent = sub; c.appendChild(s); }
    wrap.appendChild(c);
  };
  if (q.latency_ms != null) {
    const ms = q.latency_ms;
    cell("Latency", ms >= 1000 ? (ms / 1000).toFixed(2) + " s" : ms + " ms", ms >= 1000 ? `${ms.toLocaleString()} ms` : undefined);
  }
  if (q.prompt_tokens != null || q.completion_tokens != null) {
    const p = q.prompt_tokens ?? 0, c = q.completion_tokens ?? 0;
    cell("Tokens", (p + c).toLocaleString(), `${p.toLocaleString()} prompt + ${c.toLocaleString()} completion`);
  }
  if (q.cached_tokens != null) cell("Cached", q.cached_tokens.toLocaleString(), "of prompt (cache hit)");
  if (q.n_turns != null || q.n_tool_calls != null) cell("Turns", String(q.n_turns ?? 0), `${q.n_tool_calls ?? 0} tool calls`);
  return wrap;
}
// The last GENUINE reasoning a trajectory carried. Item 4: this used to fall back to a turn's
// assistant `.text`, but that text IS the model's answer (viewer_export.rs sets `answer_text` to the
// final turn's text), so "Reasoning" rendered a verbatim copy of "Model's answer text". Reasoning now
// surfaces only real reasoning (`q.reasoning` or a turn's `.reasoning`); when a trace carries none, the
// section is simply omitted rather than echoing the answer.
function lastReasoning(q: QuestionD): string {
  if (!q.trajectory || !q.trajectory.length) return "";
  for (let i = q.trajectory.length - 1; i >= 0; i--) {
    const t = q.trajectory[i];
    if (t.reasoning) return t.reasoning;
  }
  return "";
}

// ---------------------------------------------------------------------------
// Interactive stepper
// ---------------------------------------------------------------------------
function renderStepper(q: QuestionD) {
  const wrap = $("stepper");
  if (!q.trajectory || !q.trajectory.length) { wrap.classList.remove("on"); return; }
  wrap.classList.add("on");
  updateStepperBody();
}
function updateStepperBody() {
  const q = currentQuestion();
  if (!q || !q.trajectory) return;
  const n = q.trajectory.length;
  $("turnLbl").textContent = `Turn ${stepTurn + 1} / ${n}`;
  ($("stepPrev") as HTMLButtonElement).disabled = stepTurn <= 0;
  ($("stepNext") as HTMLButtonElement).disabled = stepTurn >= n - 1;
  const turn = q.trajectory[Math.max(0, stepTurn)];
  $("turnText").textContent = turn.text || (turn.reasoning ? "" : "(no assistant text this turn)");
  const calls = $("turnCalls"); calls.innerHTML = "";
  for (const c of turn.tool_calls) {
    const div = document.createElement("div"); div.className = "toolcall";
    const reg = c.region ? ` <span class="fetch">↳ fetch (${c.region.x0},${c.region.y0})–(${c.region.x1},${c.region.y1})</span>` : "";
    div.innerHTML = `${escapeHtml(c.name)}(${escapeHtml(c.args)})${reg}`;
    calls.appendChild(div);
  }
  if (!turn.tool_calls.length) {
    const div = document.createElement("div"); div.className = "toolcall"; div.textContent = "(final answer — no tool calls)";
    calls.appendChild(div);
  }
  drawBoard();
}

