// A distribution block: average / median / max stat tiles, a min·p25·p75 quantile line, and a small
// histogram (the chosen distribution descriptor). Degrades to a note when the export omits the metric.
function distBlock(label: string, vals: number[], fmt: (n: number) => string): HTMLElement {
  const b = document.createElement("div"); b.className = "statblock";
  const h = document.createElement("div"); h.className = "statssub"; h.textContent = label;
  b.appendChild(h);
  if (!vals.length) { const e = document.createElement("div"); e.className = "statempty"; e.textContent = "Not recorded in this export."; b.appendChild(e); return b; }
  const s = [...vals].sort((a, c) => a - c);
  const avg = vals.reduce((a, c) => a + c, 0) / vals.length;
  const three = document.createElement("div"); three.className = "three";
  three.appendChild(statTile("Average", fmt(avg)));
  three.appendChild(statTile("Median", fmt(quantile(s, 0.5))));
  three.appendChild(statTile("Max", fmt(s[s.length - 1])));
  b.appendChild(three);
  const q = document.createElement("div"); q.className = "statquant";
  q.textContent = `min ${fmt(s[0])} · p25 ${fmt(quantile(s, 0.25))} · p75 ${fmt(quantile(s, 0.75))} · n=${vals.length}`;
  b.appendChild(q);
  b.appendChild(histogram(s, fmt));
  return b;
}

function statTile(label: string, value: string): HTMLElement {
  const c = document.createElement("div"); c.className = "metric";
  const l = document.createElement("div"); l.className = "ml"; l.textContent = label;
  const v = document.createElement("div"); v.className = "mv"; v.textContent = value;
  c.appendChild(l); c.appendChild(v);
  return c;
}

// Linear-interpolated quantile over an ascending-sorted array.
function quantile(sorted: number[], p: number): number {
  if (!sorted.length) return 0;
  const idx = (sorted.length - 1) * p, lo = Math.floor(idx), hi = Math.ceil(idx);
  return lo === hi ? sorted[lo] : sorted[lo] + (sorted[hi] - sorted[lo]) * (idx - lo);
}

// A compact fixed-bin histogram rendered as DOM bars (theme-aware, no canvas). Each bar tooltips its
// value range and count.
function histogram(sorted: number[], fmt: (n: number) => string): HTMLElement {
  const wrap = document.createElement("div"); wrap.className = "hist";
  const BINS = 12, n = sorted.length, min = sorted[0], max = sorted[n - 1], span = max - min;
  const counts = new Array<number>(BINS).fill(0);
  for (const v of sorted) {
    let bi = span > 0 ? Math.floor((v - min) / span * BINS) : 0;
    if (bi >= BINS) bi = BINS - 1; if (bi < 0) bi = 0;
    counts[bi]++;
  }
  const cmax = Math.max(...counts, 1);
  for (let i = 0; i < BINS; i++) {
    const bar = document.createElement("div"); bar.className = "bin";
    bar.style.height = `${Math.max(1, (counts[i] / cmax) * 100)}%`;
    const lo = min + span * i / BINS, hi = min + span * (i + 1) / BINS;
    bar.title = `${fmt(lo)} – ${fmt(hi)}: ${counts[i]}`;
    wrap.appendChild(bar);
  }
  return wrap;
}

function fmtMs(ms: number): string { return ms >= 1000 ? (ms / 1000).toFixed(2) + " s" : Math.round(ms) + " ms"; }

