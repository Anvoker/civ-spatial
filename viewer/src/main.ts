function buildArgsJson(spec: ToolSpec): string {
  const parts: string[] = [];
  for (const a of spec.args) {
    const v = (toolInput(a.key)?.value ?? "").trim();
    if (v === "") continue; // omit empties — Rust returns a clear "requires …" error for missing ones
    if (a.kind === "int") parts.push(`${JSON.stringify(a.key)}:${v}`);
    else if (a.kind === "bool") parts.push(`${JSON.stringify(a.key)}:${/^(true|1|yes)$/i.test(v) ? "true" : "false"}`);
    else parts.push(`${JSON.stringify(a.key)}:${JSON.stringify(v)}`);
  }
  return `{${parts.join(",")}}`;
}

