function drawBoard() {
  const board = currentBoard();
  const q = currentQuestion();
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  if (!board) return;

  // Initialize/fit the view when the board changes.
  if (viewInitForBoard !== board.source) { fitView(board); buildOwnerColors(board); viewInitForBoard = board.source; }

  const vw = currentView(board);
  ctx.imageSmoothingEnabled = false;
  ctx.setTransform(view.scale, 0, 0, view.scale, view.tx, view.ty);
  const px = 1 / view.scale; // one screen pixel expressed in world units (screen-constant outlines)

  // Terrain: flat color base (also the fallback / water), then a sprite blit on top when available.
  for (const t of vw.tiles) {
    const wx = t.x * TILE, wy = t.y * TILE;
    ctx.fillStyle = terrainColor(t.terrain);
    ctx.fillRect(wx, wy, TILE, TILE);
    const tag = TERRAIN_SPRITE[t.terrain];
    if (tag) blitSprite(tag, wx, wy, TILE, TILE);
  }
  // Territory tint (owner-colored inset) + infrastructure markers.
  for (const t of vw.tiles) {
    const wx = t.x * TILE, wy = t.y * TILE;
    if (t.owner) {
      ctx.strokeStyle = ownerColor(t.owner);
      ctx.globalAlpha = 0.55; ctx.lineWidth = 2 * px;
      ctx.strokeRect(wx + px, wy + px, TILE - 2 * px, TILE - 2 * px);
      ctx.globalAlpha = 1;
    }
    drawExtras(t, wx, wy);
  }
  // Subtle grid when zoomed in enough to matter.
  if (view.scale * TILE >= 16) {
    ctx.strokeStyle = "rgba(0,0,0,.14)"; ctx.lineWidth = px;
    for (let x = 0; x <= board.width; x++) { ctx.beginPath(); ctx.moveTo(x * TILE, 0); ctx.lineTo(x * TILE, board.height * TILE); ctx.stroke(); }
    for (let y = 0; y <= board.height; y++) { ctx.beginPath(); ctx.moveTo(0, y * TILE); ctx.lineTo(board.width * TILE, y * TILE); ctx.stroke(); }
  }

  // Interactive: fetched-region overlays up to the current step.
  if (q && q.trajectory && stepTurn >= 0) drawFetched(q, px);

  // Cities & units — distinctly larger, owner-colored, outlined so they pop.
  for (const c of vw.cities) drawCity(c, px);
  for (const u of vw.units) drawUnit(u, px);

  // Question highlights (referents/candidates/work radius).
  if (q) drawHighlights(q, px);

  // Coordinate ruler along the top/left edges (item 6) — drawn in screen space so it stays crisp and
  // unscaled under any zoom/pan.
  drawCoordLabels(board);

  renderLegend(board);
}

// Row/column coordinate labels along the board's top and left edges (item 6). Drawn in screen space
// (identity transform) inside translucent gutters, at PERIODIC ticks whose spacing grows with zoom-out
// so 2–3 digit numbers never collide.
function drawCoordLabels(board: BoardD) {
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  const cell = TILE * view.scale;              // screen px per tile
  if (cell <= 0) return;
  const topGut = 15, leftGut = 22;             // leftGut wider to seat 3-digit row numbers
  // Visible tile range (clamp to the board).
  const wl = screenToWorld(leftGut, topGut), wr = screenToWorld(canvas.width, canvas.height);
  const x0 = Math.max(0, Math.floor(wl.x / TILE)), x1 = Math.min(board.width - 1, Math.ceil(wr.x / TILE));
  const y0 = Math.max(0, Math.floor(wl.y / TILE)), y1 = Math.min(board.height - 1, Math.ceil(wr.y / TILE));
  if (x1 < x0 || y1 < y0) return;
  const step = Math.max(1, Math.ceil(30 / cell)); // ~30px minimum between labels
  // Translucent gutters so numbers read over any terrain.
  ctx.globalAlpha = 0.82; ctx.fillStyle = cssVar("--panel");
  ctx.fillRect(0, 0, canvas.width, topGut);
  ctx.fillRect(0, 0, leftGut, canvas.height);
  ctx.globalAlpha = 1;
  ctx.fillStyle = cssVar("--muted");
  ctx.font = "10px ui-monospace, Menlo, Consolas, monospace";
  ctx.textBaseline = "middle";
  // Columns along the top.
  ctx.textAlign = "center";
  for (let x = Math.ceil(x0 / step) * step; x <= x1; x += step) {
    const sx = view.tx + (x + 0.5) * TILE * view.scale;
    if (sx <= leftGut + 4 || sx >= canvas.width - 2) continue;
    ctx.fillText(String(x), sx, topGut / 2);
  }
  // Rows along the left.
  for (let y = Math.ceil(y0 / step) * step; y <= y1; y += step) {
    const sy = view.ty + (y + 0.5) * TILE * view.scale;
    if (sy <= topGut + 4 || sy >= canvas.height - 2) continue;
    ctx.fillText(String(y), leftGut / 2, sy);
  }
}

function drawExtras(t: TileD, px: number, py: number) {
  const has = (e: string) => t.extras.includes(e);
  if (has("River")) {
    ctx.strokeStyle = "#3aa0ff"; ctx.lineWidth = Math.max(1, TILE / 8);
    ctx.beginPath(); ctx.moveTo(px + TILE * 0.2, py); ctx.lineTo(px + TILE * 0.6, py + TILE); ctx.stroke();
  }
  if (has("Railroad")) {
    ctx.strokeStyle = "#111"; ctx.lineWidth = Math.max(1, TILE / 9);
    ctx.beginPath(); ctx.moveTo(px, py + TILE / 2); ctx.lineTo(px + TILE, py + TILE / 2); ctx.stroke();
  } else if (has("Road")) {
    ctx.strokeStyle = "#6b5b3e"; ctx.lineWidth = Math.max(1, TILE / 12);
    ctx.beginPath(); ctx.moveTo(px, py + TILE / 2); ctx.lineTo(px + TILE, py + TILE / 2); ctx.stroke();
  }
  // A resource / special extra dot (anything that isn't infrastructure/terrain feature).
  const infra = new Set(["River", "Road", "Railroad", "Irrigation", "Mine", "Farmland", "Fortress", "Airbase", "Pollution", "Fallout", "Hut"]);
  if (t.extras.some(e => !infra.has(e))) {
    ctx.fillStyle = "#fff"; ctx.strokeStyle = "#b8860b"; ctx.lineWidth = 1;
    ctx.beginPath(); ctx.arc(px + TILE * 0.78, py + TILE * 0.22, TILE / 7, 0, Math.PI * 2);
    ctx.fill(); ctx.stroke();
  }
}

// A bold, legible owner ring drawn ON TOP of a sprite: a dark backing stroke plus the owner color,
// so it reads on any terrain and isn't hidden under the sprite art.
function ownerRing(wx: number, wy: number, oc: string, px: number) {
  const x = wx + 1.75 * px, y = wy + 1.75 * px, w = TILE - 3.5 * px, h = TILE - 3.5 * px;
  ctx.strokeStyle = "rgba(0,0,0,.7)"; ctx.lineWidth = 4 * px; ctx.strokeRect(x, y, w, h);
  ctx.strokeStyle = oc; ctx.lineWidth = 2.5 * px; ctx.strokeRect(x, y, w, h);
}

function drawCity(c: CityD, px: number) {
  const wx = c.x * TILE, wy = c.y * TILE;
  const oc = ownerColor(c.owner);
  if (!blitSprite(cityTag(c.size), wx, wy, TILE, TILE)) {
    // Fallback: a filled owner-colored diamond with white outline.
    const cx = wx + TILE / 2, cy = wy + TILE / 2, r = TILE * 0.42;
    ctx.fillStyle = oc; ctx.strokeStyle = "#fff"; ctx.lineWidth = 2 * px;
    ctx.beginPath();
    ctx.moveTo(cx, cy - r); ctx.lineTo(cx + r, cy); ctx.lineTo(cx, cy + r); ctx.lineTo(cx - r, cy); ctx.closePath();
    ctx.fill(); ctx.stroke();
  }
  // Bold owner ring ON TOP so the city's owner reads even under the sprite.
  ownerRing(wx, wy, oc, px);
  // Size badge bottom-right + optional name label at higher zoom.
  drawBadge(String(c.size), wx + TILE, wy + TILE, oc, px, "br");
  if (view.scale >= 1.1 && c.name) drawLabel(c.name, wx + TILE / 2, wy - 2 * px, px);
}

function drawUnit(u: UnitD, px: number) {
  const wx = u.x * TILE, wy = u.y * TILE;
  const oc = ownerColor(u.owner);
  // Owner-colored rounded chip behind the sprite so units pop; sprite (or a fallback marker) on top.
  const inset = TILE * 0.14;
  ctx.fillStyle = oc; ctx.globalAlpha = 0.9;
  roundRect(wx + inset, wy + inset, TILE - 2 * inset, TILE - 2 * inset, 4 * px);
  ctx.fill(); ctx.globalAlpha = 1;
  ctx.strokeStyle = "rgba(0,0,0,.65)"; ctx.lineWidth = 1.5 * px; ctx.stroke();
  if (!blitSprite(unitTag(u.kind), wx, wy, TILE, TILE)) {
    const cx = wx + TILE / 2, cy = wy + TILE / 2, r = TILE * 0.3;
    ctx.fillStyle = "#fff"; ctx.strokeStyle = oc; ctx.lineWidth = 2 * px;
    ctx.beginPath(); ctx.arc(cx, cy, r, 0, Math.PI * 2); ctx.fill(); ctx.stroke();
  }
  // Bold owner ring ON TOP so the unit's owner reads even under the sprite.
  ownerRing(wx, wy, oc, px);
}

function roundRect(x: number, y: number, w: number, h: number, r: number) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}
// A small filled badge with text (e.g. city size). Anchored at a tile corner.
function drawBadge(text: string, ax: number, ay: number, color: string, px: number, _anchor: "br") {
  const s = 11 * px;
  const cx = ax - s, cy = ay - s;
  ctx.fillStyle = color; ctx.strokeStyle = "#fff"; ctx.lineWidth = 1.5 * px;
  ctx.beginPath(); ctx.arc(cx, cy, s, 0, Math.PI * 2); ctx.fill(); ctx.stroke();
  ctx.fillStyle = "#fff"; ctx.font = `${Math.round(13 * px)}px sans-serif`;
  ctx.textAlign = "center"; ctx.textBaseline = "middle";
  ctx.fillText(text, cx, cy + 0.5 * px);
}
// A small numbered badge anchored at a tile's top-left corner (candidate index). Dark disc + light
// text so it stays legible over the cyan candidate fill and any terrain.
function drawIndexBadge(text: string, tx: number, ty: number, ring: string, px: number) {
  const s = 8.5 * px, cx = tx + s + 1.5 * px, cy = ty + s + 1.5 * px;
  ctx.fillStyle = "rgba(0,0,0,.82)"; ctx.strokeStyle = ring; ctx.lineWidth = 1.75 * px;
  ctx.beginPath(); ctx.arc(cx, cy, s, 0, Math.PI * 2); ctx.fill(); ctx.stroke();
  ctx.fillStyle = "#fff"; ctx.font = `700 ${Math.round(11 * px)}px sans-serif`;
  ctx.textAlign = "center"; ctx.textBaseline = "middle";
  ctx.fillText(text, cx, cy + 0.5 * px);
}
// A short label with a readable pill behind it (drawn only when zoomed in).
function drawLabel(text: string, cx: number, baseY: number, px: number) {
  ctx.font = `${Math.round(12 * px)}px system-ui, sans-serif`;
  ctx.textAlign = "center"; ctx.textBaseline = "bottom";
  const w = ctx.measureText(text).width + 6 * px, h = 15 * px;
  ctx.fillStyle = "rgba(0,0,0,.62)";
  roundRect(cx - w / 2, baseY - h, w, h, 3 * px); ctx.fill();
  ctx.fillStyle = "#fff"; ctx.fillText(text, cx, baseY - 2 * px);
}

function drawFetched(q: QuestionD, px: number) {
  const traj = q.trajectory!;
  for (let i = 0; i <= stepTurn && i < traj.length; i++) {
    const isCurrent = i === stepTurn;
    for (const b of traj[i].fetched_regions) {
      ctx.fillStyle = cssVar("--fetch");
      ctx.globalAlpha = isCurrent ? 0.34 : 0.14;
      ctx.fillRect(b.x0 * TILE, b.y0 * TILE, (b.x1 - b.x0 + 1) * TILE, (b.y1 - b.y0 + 1) * TILE);
      ctx.globalAlpha = 1;
      if (isCurrent) {
        ctx.strokeStyle = cssVar("--fetch"); ctx.lineWidth = 2.5 * px;
        ctx.strokeRect(b.x0 * TILE + px, b.y0 * TILE + px, (b.x1 - b.x0 + 1) * TILE - 2 * px, (b.y1 - b.y0 + 1) * TILE - 2 * px);
      }
    }
  }
}

function drawHighlights(q: QuestionD, px: number) {
  // Work-radius rings (region-count / best-site) around referents/candidates.
  if (q.radius != null) {
    const centers = q.referents.length ? q.referents : q.candidates;
    ctx.strokeStyle = cssVar("--cand"); ctx.lineWidth = 2 * px; ctx.globalAlpha = 0.7;
    for (const p of centers) {
      const x0 = (p.x - q.radius) * TILE, y0 = (p.y - q.radius) * TILE;
      const side = (2 * q.radius + 1) * TILE;
      ctx.strokeRect(x0 + px, y0 + px, side - 2 * px, side - 2 * px);
    }
    ctx.globalAlpha = 1;
  }
  // Candidates: translucent cyan fill + outline, each stamped with its 1-based index. The number is
  // the candidate's position in the option list the model chose from (see the "candidate #" legend).
  q.candidates.forEach((p, i) => {
    ctx.fillStyle = cssVar("--cand"); ctx.globalAlpha = 0.3;
    ctx.fillRect(p.x * TILE, p.y * TILE, TILE, TILE);
    ctx.globalAlpha = 1;
    ctx.strokeStyle = cssVar("--cand"); ctx.lineWidth = 3 * px;
    ctx.strokeRect(p.x * TILE + 1.5 * px, p.y * TILE + 1.5 * px, TILE - 3 * px, TILE - 3 * px);
    // Index badge anchored top-LEFT (city size sits bottom-right, resource dot top-right).
    drawIndexBadge(String(i + 1), p.x * TILE, p.y * TILE, cssVar("--cand"), px);
  });
  // Referents: bright amber ring + corner crosshair so they're findable at any zoom.
  for (const p of q.referents) {
    ctx.strokeStyle = cssVar("--ref"); ctx.lineWidth = 3.5 * px;
    ctx.strokeRect(p.x * TILE + 1.5 * px, p.y * TILE + 1.5 * px, TILE - 3 * px, TILE - 3 * px);
    const cx = p.x * TILE + TILE / 2, cy = p.y * TILE + TILE / 2, r = TILE * 0.9;
    ctx.beginPath(); ctx.moveTo(cx - r, cy); ctx.lineTo(cx - TILE * 0.35, cy);
    ctx.moveTo(cx + TILE * 0.35, cy); ctx.lineTo(cx + r, cy);
    ctx.moveTo(cx, cy - r); ctx.lineTo(cx, cy - TILE * 0.35);
    ctx.moveTo(cx, cy + TILE * 0.35); ctx.lineTo(cx, cy + r); ctx.stroke();
  }
}

function renderLegend(board: BoardD) {
  const vw = currentView(board);
  const present = new Set(vw.tiles.map(t => t.terrain));
  // Faction colors first (rendered into #ownerLegend, which sits ABOVE #legend in the DOM).
  renderOwnerLegend(board);
  const host = $("legend"); host.innerHTML = "";
  // Then the most-important markers: referent / candidate / fetched-region (item 3).
  host.appendChild(swatch(cssVar("--ref"), "referent", true));
  host.appendChild(swatch(cssVar("--cand"), "candidate", true));
  host.appendChild(markerLegend("candidate # = option index (top-left)"));
  const q = currentQuestion();
  if (q && q.trajectory) host.appendChild(swatch(cssVar("--fetch"), "fetched region", true));
  host.appendChild(markerLegend("size # = city population (bottom-right)"));
  // Terrain swatches last. (The City/Unit rows are gone — they're drawn as sprites, so the rows were
  // useless — item 3.)
  for (const name of Object.keys(TERRAIN_COLORS)) {
    if (!present.has(name)) continue;
    host.appendChild(swatch(terrainColor(name), name));
  }
}
function swatch(color: string, label: string, outline = false): HTMLElement {
  const s = document.createElement("span"); s.className = "sw";
  const chip = document.createElement("span"); chip.className = "chip";
  if (outline) { chip.style.background = "transparent"; chip.style.border = `2px solid ${color}`; }
  else chip.style.background = color;
  s.appendChild(chip); s.appendChild(document.createTextNode(label));
  return s;
}
function markerLegend(text: string): HTMLElement {
  const s = document.createElement("span"); s.className = "sw"; s.textContent = text; return s;
}

// Owner legend: swatch -> player name (the color used for that player's cities/units/territory ring),
// in the same stable order as the color assignment. The perspective player ("you") is flagged.
function renderOwnerLegend(board: BoardD) {
  const host = $("ownerLegend"); if (!host) return;
  host.innerHTML = "";
  if (!ownerOrder.length) { host.appendChild(markerLegend("(no owned tiles/objects)")); return; }
  const you = board.perspective;
  for (const name of ownerOrder) {
    const isYou = !!you && name === you;
    const s = document.createElement("span");
    s.className = "sw owner" + (isYou ? " you" : "");
    const chip = document.createElement("span"); chip.className = "chip";
    chip.style.background = ownerColorMap[name]; chip.style.borderColor = "rgba(0,0,0,.55)";
    s.appendChild(chip);
    // Label by nation; keep the (deduped) leader name as a small secondary when it differs.
    const nation = ownerLabel(name);
    let text = nation + (isYou ? "  (you)" : "");
    if (nation !== name) text += `  ·  ${name}`;
    s.appendChild(document.createTextNode(text));
    host.appendChild(s);
  }
}

